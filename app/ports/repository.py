"""Contrato mínimo de persistencia que necesita la shell."""
from typing import Protocol

from app.domain.models import Member, Project, Task, WorkPackage


class PersistenceError(Exception):
    """Error de infraestructura (no es un error de dominio)."""


class Repository(Protocol):
    def add_project(self, project: Project) -> Project: ...
    def get_project(self, project_id: int) -> Project | None: ...
    def list_projects(self) -> tuple[Project, ...]: ...
    def add_member(self, member: Member) -> Member: ...
    def list_members(self, project_id: int) -> tuple[Member, ...]: ...
    def add_package(self, package: WorkPackage) -> WorkPackage: ...
    def list_packages(self, project_id: int) -> tuple[WorkPackage, ...]: ...
    def add_task(self, task: Task) -> Task: ...
    def get_task(self, task_id: int) -> Task | None: ...
    def list_tasks(self, project_id: int) -> tuple[Task, ...]: ...
    def update_task(self, task: Task) -> Task: ...
